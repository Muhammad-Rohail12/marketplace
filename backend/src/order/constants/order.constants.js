const STATUS = {
  PENDING_PAYMENT: 'PENDING_PAYMENT',
  PAID: 'PAID',
  PROCESSING: 'PROCESSING',
  SHIPPED: 'SHIPPED',
  DELIVERED: 'DELIVERED',
  CANCELLED: 'CANCELLED',
  REFUNDED: 'REFUNDED',
};

// Single source of truth state machine — mirrors the pattern
// established in Phase 20 (SellerApplication) and Phase 22 (Product).
const ALLOWED_TRANSITIONS = {
  [STATUS.PENDING_PAYMENT]: [STATUS.PAID, STATUS.CANCELLED],
  [STATUS.PAID]: [STATUS.PROCESSING, STATUS.CANCELLED, STATUS.REFUNDED],
  [STATUS.PROCESSING]: [STATUS.SHIPPED, STATUS.CANCELLED, STATUS.REFUNDED],
  [STATUS.SHIPPED]: [STATUS.DELIVERED, STATUS.REFUNDED],
  [STATUS.DELIVERED]: [STATUS.REFUNDED],
  [STATUS.CANCELLED]: [],
  [STATUS.REFUNDED]: [],
};

// Statuses at/before which a BUYER may self-cancel without seller/
// admin intervention — once a seller has started fulfillment
// (PROCESSING+), only the seller/admin can cancel.
const BUYER_CANCELLABLE_STATUSES = [STATUS.PENDING_PAYMENT, STATUS.PAID];
const SELLER_CANCELLABLE_STATUSES = [STATUS.PAID, STATUS.PROCESSING];

const PAYMENT_STATUS = { PENDING: 'PENDING', PAID: 'PAID', FAILED: 'FAILED', REFUNDED: 'REFUNDED', PARTIALLY_REFUNDED: 'PARTIALLY_REFUNDED' };

const ALLOWED_SORT_FIELDS = ['createdAt', 'grandTotal', 'status'];

module.exports = { STATUS, ALLOWED_TRANSITIONS, BUYER_CANCELLABLE_STATUSES, SELLER_CANCELLABLE_STATUSES, PAYMENT_STATUS, ALLOWED_SORT_FIELDS };